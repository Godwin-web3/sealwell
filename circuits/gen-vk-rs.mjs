// Emit contracts/sealwell-auction/src/vk.rs from build/verification_key.json (NEAR LE encodings).
import fs from "fs"; import { g1, g2 } from "./lib.mjs";
const vk = JSON.parse(fs.readFileSync(new URL("./build/verification_key.json", import.meta.url)));
const h = (b) => `"${b.toString("hex")}"`;
const out = `// GENERATED by circuits/gen-vk-rs.mjs from circuits/build/verification_key.json. Do not edit.
// Hackathon-only trusted setup (see circuits/SETUP.md). NOT production.
pub const N_PUBLIC: usize = ${vk.nPublic};
pub const ALPHA_G1: &str = ${h(g1(vk.vk_alpha_1))};
pub const BETA_G2: &str = ${h(g2(vk.vk_beta_2))};
pub const GAMMA_G2: &str = ${h(g2(vk.vk_gamma_2))};
pub const DELTA_G2: &str = ${h(g2(vk.vk_delta_2))};
pub const IC: [&str; ${vk.IC.length}] = [${vk.IC.map((p) => h(g1(p))).join(", ")}];
`;
fs.writeFileSync(new URL("../contracts/sealwell-auction/src/vk.rs", import.meta.url), out); console.log("wrote vk.rs");
